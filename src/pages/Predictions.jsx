
import { useState } from "react";
import DashboardLayout from "../layouts/DashboardLayout.jsx";
import PageHeader from "../components/PageHeader.jsx";
import PredictionCard from "../components/PredictionCard.jsx";
import { predictions } from "../data/mockData.js";

import {
  sendTemperatureReading,
  resetTemperatureTestHistory,
} from "../services/temperatureApi.js";


function formatLocalTimestamp(date) {
  const pad = (n) => String(n).padStart(2, "0");

  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(
    date.getDate()
  )} ${pad(date.getHours())}:${pad(date.getMinutes())}:${pad(
    date.getSeconds()
  )}`;
}


export default function Predictions() {
  const [showTestForm, setShowTestForm] = useState(false);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [result, setResult] = useState(null);

  const [readings, setReadings] = useState({
    current: "",
    five: "",
    ten: "",
    fifteen: "",
  });


  function updateReading(field, value) {
    setReadings((previous) => ({
      ...previous,
      [field]: value,
    }));
  }


  async function handlePrediction(event) {
    event.preventDefault();

    setError("");
    setResult(null);

    const values = Object.values(readings);

    if (values.some((value) => value.trim() === "")) {
      setError(
        "Please enter all four temperature readings."
      );
      return;
    }

    if (
      values.some(
        (value) => !Number.isFinite(Number(value))
      )
    ) {
      setError(
        "Please enter valid numeric temperatures."
      );
      return;
    }

    if (
      values.some(
        (value) => Number(value) < 0 || Number(value) > 50
      )
    ) {
      setError(
        "Temperature readings must be between 0°C and 50°C."
      );
      return;
    }

    setLoading(true);

    try {
      // Clear previous manual test history.
      await resetTemperatureTestHistory();

      const latestTime = new Date();

      const sequence = [
        { minutesAgo: 15, value: readings.fifteen },
        { minutesAgo: 10, value: readings.ten },
        { minutesAgo: 5, value: readings.five },
        { minutesAgo: 0, value: readings.current },
      ];

      let responseData = null;

      for (const reading of sequence) {
        const timestamp = new Date(
          latestTime.getTime() -
            reading.minutesAgo * 60 * 1000
        );

        responseData = await sendTemperatureReading(
          formatLocalTimestamp(timestamp),
          reading.value
        );
      }

      if (responseData.status === "success") {
        setResult(responseData);
      } else {
        setError(
          responseData.message ||
            "The model is waiting for valid history."
        );
      }

    } catch (err) {
      setError(
        err.message ||
          "Could not connect to the Flask backend."
      );

    } finally {
      setLoading(false);
    }
  }


  const updatedPredictions = predictions.map((prediction) => {
    if (prediction.id !== "temp" || !result) {
      return prediction;
    }

    return {
      ...prediction,

      body:
        "30-minute temperature forecast generated by the trained ML model using test readings.",

      current: `${result.current_temperature_c}°C`,

      predicted: `${result.predicted_temperature_c}°C`,

      window: "30 minutes",

      recommendation:
        `Forecast for ${result.forecast_timestamp.replace(
          "T",
          " "
        )}. Test data only.`,
    };
  });


  return (
    <DashboardLayout>

      <PageHeader
        title="AI Predictions"
        subtitle="Forecasts generated from recent sensor trends"
      />


      {/* Temperature Model Testing */}

      <div className="mb-5 panel p-5">

        <div className="flex items-center justify-between gap-3">

          <div>
            <h2 className="text-white font-medium">
              Temperature Model Testing
            </h2>

            <p className="text-sm text-slate-400 mt-1">
              ESP32 integration is pending. Use manual test readings for now.
            </p>
          </div>


          <button
            type="button"
            onClick={() => setShowTestForm(!showTestForm)}
            className="rounded-lg bg-aqua-600 px-4 py-2 text-sm text-white hover:bg-aqua-500"
          >
            {showTestForm
              ? "Close"
              : "Test Temperature Prediction"}
          </button>

        </div>


        {showTestForm && (

          <form
            onSubmit={handlePrediction}
            className="mt-5 space-y-4"
          >

            <p className="text-xs text-amber-300">
              TEST MODE — These readings are manually entered,
              not live sensor data.
            </p>


            <div className="grid sm:grid-cols-2 gap-4">

              {[
                ["fifteen", "Temperature 15 minutes ago (°C)"],
                ["ten", "Temperature 10 minutes ago (°C)"],
                ["five", "Temperature 5 minutes ago (°C)"],
                ["current", "Current temperature (°C)"],
              ].map(([field, label]) => (

                <label key={field} className="block">

                  <span className="text-sm text-slate-300">
                    {label}
                  </span>

                  <input
                    type="number"
                    step="any"
                    min="0"
                    max="50"
                    required
                    value={readings[field]}
                    onChange={(event) =>
                      updateReading(field, event.target.value)
                    }
                    placeholder="Enter temperature"
                    className="mt-2 w-full rounded-lg border border-border bg-slate-900 p-3 text-white outline-none focus:border-aqua-400"
                  />

                </label>

              ))}

            </div>


            {error && (
              <p className="text-sm text-red-400">
                {error}
              </p>
            )}


            <button
              type="submit"
              disabled={loading}
              className="rounded-lg bg-aqua-600 px-5 py-2.5 text-sm text-white hover:bg-aqua-500 disabled:opacity-50"
            >
              {loading
                ? "Generating prediction..."
                : "Generate Prediction"}
            </button>

          </form>

        )}

      </div>


      {/* Successful Prediction Information */}

      {result && (

        <div className="mb-5 rounded-lg border border-green-500/30 bg-green-500/10 p-4">

          <p className="text-green-400 font-medium">
            Temperature prediction generated successfully!
          </p>

          <p className="mt-1 text-sm text-slate-300">
            Forecast horizon: {result.forecast_horizon_minutes} minutes
          </p>

          <p className="text-xs text-slate-400 mt-1">
            Model version: {result.model_version}
          </p>

        </div>

      )}


      {/* Prediction Cards */}

      <div className="grid lg:grid-cols-2 gap-5">

        {updatedPredictions.map((prediction) => (

          <PredictionCard
            key={prediction.id}
            prediction={prediction}
          />

        ))}

      </div>

    </DashboardLayout>
  );
}
